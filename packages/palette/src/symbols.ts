export const symbolItems = (): ModeItem[] =>
  SYMBOLS.flatMap(([group, symbols]) =>
    symbols.map(([symbol, name, keywords]) => ({
      id: `symbol:${name}`,
      // Spaces would show as nothing, so they show as ␣.
      title: `${/^[\s\u200b]+$/.test(symbol) ? '␣' : symbol}  ${name}`,
      keywords: keywords ?? '',
      copy: symbol,
      group,
    })),
  );
