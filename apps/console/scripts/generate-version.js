#!/usr/bin/env node

/**
 * Version Generation Script
 *
 * This script generates version information for the app including:
 * - Version number (from version.json)
 * - Build timestamp (ISO format)
 * - Git commit hash (if available)
 *
 * Output is written to src/version.ts for importing in the app
 */

const fs = require('node:fs');
const path = require('node:path');
const { execSync } = require('node:child_process');

// Read version from version.json
const versionPath = path.join(__dirname, '..', 'version.json');
const version = JSON.parse(fs.readFileSync(versionPath, 'utf-8'));

// Generate build timestamp in ISO format
const buildTime = new Date().toISOString();

// Try to get git commit hash
let gitHash = 'unknown';
try {
  gitHash = execSync('git rev-parse --short HEAD', { encoding: 'utf-8' }).trim();
} catch (e) {
  console.warn('Could not get git commit hash:', e.message);
}

// Create version string
const versionString = `${version.major}.${version.minor}.${version.patch}`;

// Generate TypeScript file
const outputPath = path.join(__dirname, '..', 'src', 'version.ts');
const content = `// This file is auto-generated by scripts/generate-version.js
// Do not edit manually

export const VERSION = {
  version: '${versionString}',
  buildTime: '${buildTime}',
  gitHash: '${gitHash}',
  full: 'v${versionString}+${gitHash}'
} as const;
`;

fs.writeFileSync(outputPath, content, 'utf-8');
console.log(`✓ Generated version info: ${versionString} (${buildTime})`);
